"""
Reproducible comparison of VibeMatch 1.0 (baseline) and VibeMatch 2.0 (evaluate-and-revise).

    python -m src.evaluate                 # writes evaluation/results.json and evaluation/summary.md
    python -m src.evaluate --out-dir DIR   # write somewhere else

Both versions share the same catalog and profiles. "Baseline" is the original Module 3
recommend_songs() output, which is also the first step of the 2.0 pipeline. All numbers are
offline, rule-based metrics from src/evaluator.py. They measure agreement with the stated
preferences and list diversity, not listener satisfaction.

The output contains no timestamps, so re-running on the same code and data produces
byte-identical files.
"""

import argparse
import json
import os
from typing import Dict, List

from src.agent import PipelineResult, run_pipeline
from src.guardrails import load_catalog
from src.main import EVALUATION_PROFILES

K = 5
COMPARED = [
    # (metric, label, direction) - direction +1 means higher is better
    ("genre_matches", "genre matches", +1),
    ("mood_matches", "mood matches", +1),
    ("mean_energy_distance", "mean energy gap", -1),
    ("energy_violations", "energy violations", -1),
    ("off_target", "off-target songs", -1),
    ("unique_artists", "unique artists", +1),
    ("unique_genres", "unique genres", +1),
]


def compare(result: PipelineResult) -> Dict[str, Dict]:
    """Per-metric baseline vs. final values and whether 2.0 is better, worse or the same."""
    base, final = result.baseline_eval.metrics, result.final_eval.metrics
    out = {}
    for metric, _, direction in COMPARED:
        b, f = base.get(metric), final.get(metric)
        if b is None or f is None:
            change = "n/a"
        elif f == b:
            change = "same"
        else:
            change = "better" if (f - b) * direction > 0 else "worse"
        out[metric] = {"baseline": b, "final": f, "change": change}
    out["warnings"] = {"baseline": len(result.baseline_eval.warnings), "final": len(result.final_eval.warnings),
                       "change": "same" if len(result.baseline_eval.warnings) == len(result.final_eval.warnings)
                       else "better" if len(result.final_eval.warnings) < len(result.baseline_eval.warnings) else "worse"}
    return out


def build_report(data_path: str = "data/songs.csv") -> Dict:
    catalog = load_catalog(data_path)
    profiles = []
    for name, prefs in EVALUATION_PROFILES.items():
        result = run_pipeline(prefs, catalog.songs, K)
        full = result.to_dict()
        profiles.append({
            "profile": name,
            "input": prefs,
            "outcome": result.outcome,
            "revision_activated": result.revision_activated,
            "revision_accepted": result.revision_accepted,
            "final_config": result.final_config,
            "baseline_titles": [i.song["title"] for i in result.baseline],
            "final_titles": [i.song["title"] for i in result.final],
            "baseline_verdict": result.baseline_eval.verdict,
            "final_verdict": result.final_eval.verdict,
            "comparison": compare(result),
            "baseline_issues": [i.message for i in result.baseline_eval.warnings],
            "final_issues": [i.message for i in result.final_eval.warnings],
            "limitations": result.limitations,
            "attempts": [{"strategy": a.strategy, "targeted_issues": a.targeted_issues, "titles": a.titles,
                          "accepted": a.accepted, "reasons": a.reasons} for a in result.attempts],
            "audit": result.audit,
            "detail": {"baseline": full["baseline"], "final": full["final"],
                       "baseline_evaluation": full["baseline_evaluation"],
                       "final_evaluation": full["final_evaluation"]},
        })
    return {
        "description": "VibeMatch 1.0 baseline vs. VibeMatch 2.0 final recommendations (k=5). "
                       "Metrics are rule-based agreement with stated preferences, not user satisfaction.",
        "command": "python -m src.evaluate",
        "catalog": {"path": data_path, "songs": len(catalog.songs), "warnings": catalog.warnings},
        "k": K,
        "profiles": profiles,
    }


def _fmt(value) -> str:
    if value is None:
        return "n/a"
    return f"{value:.3f}" if isinstance(value, float) else str(value)


def render_markdown(report: Dict) -> str:
    lines: List[str] = [
        "# VibeMatch 1.0 vs. 2.0: Evaluation Summary",
        "",
        "Generated by `python -m src.evaluate` from `data/songs.csv` "
        f"({report['catalog']['songs']} songs), k={report['k']}. Raw data: [`results.json`](results.json).",
        "",
        "> These are offline, rule-based metrics: how well each list matches the *stated* genre, mood and "
        "energy, and how varied it is. They are not measurements of listener satisfaction or real-world "
        "accuracy. No users were involved.",
        "",
        "## Overview",
        "",
        "| Profile | Revision activated | Decision | Baseline verdict | Final verdict | Warnings (base → final) |",
        "|---|---|---|---|---|---|",
    ]
    for p in report["profiles"]:
        decision = "accepted" if p["revision_accepted"] else ("rejected" if p["revision_activated"] else "not needed")
        w = p["comparison"]["warnings"]
        lines.append(f"| {p['profile']} | {'yes' if p['revision_activated'] else 'no'} | {decision} | "
                     f"{p['baseline_verdict']} | {p['final_verdict']} | {w['baseline']} → {w['final']} |")

    lines += ["", "## Where 2.0 was better, worse, or unchanged", "",
              "| Profile | Better | Worse | Unchanged |", "|---|---|---|---|"]
    for p in report["profiles"]:
        groups = {"better": [], "worse": [], "same": []}
        for metric, label, _ in COMPARED:
            change = p["comparison"][metric]["change"]
            if change in groups:
                groups[change].append(label)
        lines.append(f"| {p['profile']} | {', '.join(groups['better']) or '-'} | "
                     f"{', '.join(groups['worse']) or '-'} | {len(groups['same'])} metric(s) |")

    for p in report["profiles"]:
        lines += ["", f"## {p['profile']}", "",
                  "**Input:** `" + json.dumps(p["input"]) + "`", "",
                  f"**Outcome:** {p['outcome']} (final config: {p['final_config']})", "",
                  "| # | Baseline (1.0) | Final (2.0) |", "|---|---|---|"]
        for i, (b, f) in enumerate(zip(p["baseline_titles"], p["final_titles"]), start=1):
            mark = "" if b == f else " ⟵ changed"
            lines.append(f"| {i} | {b} | {f}{mark} |")
        lines += ["", "| Metric | Baseline | Final | Change |", "|---|---|---|---|"]
        for metric, label, _ in COMPARED:
            c = p["comparison"][metric]
            lines.append(f"| {label} | {_fmt(c['baseline'])} | {_fmt(c['final'])} | {c['change']} |")
        c = p["comparison"]["warnings"]
        lines.append(f"| warning-level issues | {c['baseline']} | {c['final']} | {c['change']} |")
        if p["baseline_issues"]:
            lines += ["", "Baseline issues: " + " ".join(p["baseline_issues"])]
        if p["final_issues"] and p["final_issues"] != p["baseline_issues"]:
            lines += ["", "Remaining issues: " + " ".join(p["final_issues"])]
        elif p["final_issues"]:
            lines += ["", "Issues remain unresolved in the final list."]
        for n, a in enumerate(p["attempts"], start=1):
            if not a["accepted"]:
                lines += ["", f"Rejected candidate (attempt {n}, `{a['strategy']}`): " + ", ".join(a["titles"]),
                          "", "Reason: " + "; ".join(a["reasons"])]
        if p["limitations"]:
            lines += ["", "Catalog limitations reported to the user:", ""] + [f"- {l}" for l in p["limitations"]]
        lines += ["", "Audit trail:", ""] + [f"- {s}" for s in p["audit"]]
    lines.append("")
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Compare VibeMatch 1.0 and 2.0 on the evaluation profiles")
    parser.add_argument("--data", default="data/songs.csv")
    parser.add_argument("--out-dir", default="evaluation")
    args = parser.parse_args(argv)

    report = build_report(args.data)
    os.makedirs(args.out_dir, exist_ok=True)
    json_path = os.path.join(args.out_dir, "results.json")
    md_path = os.path.join(args.out_dir, "summary.md")
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)
        f.write("\n")
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(render_markdown(report))

    for p in report["profiles"]:
        w = p["comparison"]["warnings"]
        print(f"{p['profile']:<42} {p['outcome']:<34} warnings {w['baseline']} -> {w['final']}")
    print(f"\nWrote {json_path} and {md_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
